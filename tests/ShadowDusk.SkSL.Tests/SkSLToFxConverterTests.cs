using Shouldly;
using ShadowDusk.ShaderToy;
using Xunit;

namespace ShadowDusk.SkSL.Tests;

public sealed class SkSLToFxConverterTests
{
    private const string Plain = """
        uniform float2 size;
        uniform half4 tint;
        half4 main(float2 coord) {
            half2 uv = coord / size;
            return half4(uv, 0.5, 1) * tint;
        }
        """;

    private static string Succeeds(string sksl, ConvertOptions? options = null)
    {
        ConvertResult r = SkSLToFxConverter.Convert(sksl, options);
        r.Success.ShouldBeTrue(string.Join("; ", r.Diagnostics.Select(d => d.Message)));
        r.Fx.ShouldNotBeNull();
        return r.Fx;
    }

    private static ConvertDiagnostic FailsWith(string sksl, string construct)
    {
        ConvertResult r = SkSLToFxConverter.Convert(sksl);
        r.Success.ShouldBeFalse();
        r.Fx.ShouldBeNull();
        ConvertDiagnostic d = r.Diagnostics.ShouldHaveSingleItem();
        d.Severity.ShouldBe(DiagnosticSeverity.Error);
        d.Construct.ShouldBe(construct);
        d.Message.ShouldNotContain("ShaderToy", Case.Sensitive);
        d.Message.ShouldNotContain("mainImage(", Case.Sensitive);
        return d;
    }

    [Fact]
    public void Convert_PlainColorShader_Succeeds()
    {
        ConvertResult r = SkSLToFxConverter.Convert(Plain);

        r.Success.ShouldBeTrue(string.Join("; ", r.Diagnostics.Select(d => d.Message)));
        r.Fx.ShouldNotBeNull();
        r.Fx.ShouldContain("float4 mainImage(float2 coord)", Case.Sensitive);
        r.UsedUniforms.ShouldBe(new[] { "iResolution", "size", "tint" }, ignoreOrder: true);
    }

    [Fact]
    public void Convert_PassesTopLeftPixelCoordinates()
    {
        string fx = Succeeds(Plain);

        // SkSL coords are pixel centers with a top-left origin: uv (top-left origin) times the size.
        fx.ShouldContain(
            "float4 PSMain(VSOutput input) : COLOR0\n{\n    return mainImage(input.UV * iResolution.xy);\n}\n",
            Case.Sensitive);
        fx.ShouldNotContain("1.0 - input.UV.y", Case.Sensitive);
        fx.ShouldNotContain("iResolution.y -", Case.Sensitive);
    }

    [Fact]
    public void Convert_HeaderStatesTheSkSLHostContract()
    {
        string fx = Succeeds(Plain);

        fx.ShouldContain("generated by ShadowDusk SkSL frontend", Case.Sensitive);
        fx.ShouldContain("SkSL (default): premultiplied textures, BlendState.AlphaBlend.", Case.Sensitive);
        fx.ShouldContain("SkSLStraightAlpha: straight-alpha textures, BlendState.NonPremultiplied.", Case.Sensitive);
        fx.ShouldContain("<child>TexelSize", Case.Sensitive);
    }

    [Fact]
    public void Convert_EmitsPremultipliedThenStraightAlphaTechniques()
    {
        string fx = Succeeds(Plain);

        int premultiplied = fx.IndexOf($"technique {SkSLToFxConverter.PremultipliedTechniqueName}\n", StringComparison.Ordinal);
        int straight = fx.IndexOf($"technique {SkSLToFxConverter.StraightAlphaTechniqueName}\n", StringComparison.Ordinal);
        premultiplied.ShouldBeGreaterThanOrEqualTo(0);
        straight.ShouldBeGreaterThan(premultiplied);
        fx.ShouldContain("PixelShader  = compile PS_SHADERMODEL PSMain();", Case.Sensitive);
        fx.ShouldContain("PixelShader  = compile PS_SHADERMODEL PSMainStraightAlpha();", Case.Sensitive);
    }

    [Fact]
    public void Convert_StraightAlphaTechnique_UnpremultipliesTheResult() =>
        Succeeds(Plain).ShouldContain(
            "float4 PSMainStraightAlpha(VSOutput input) : COLOR0\n{\n" +
            "    float4 color = mainImage(input.UV * iResolution.xy);\n" +
            "    return float4(color.rgb / max(color.a, 0.0001), color.a);\n}\n",
            Case.Sensitive);

    [Fact]
    public void Convert_WithoutChildren_HasNoStraightAlphaFlag() =>
        Succeeds(Plain).ShouldNotContain("sd_", Case.Sensitive);

    [Fact]
    public void Convert_WithChildren_EachTechniqueSetsTheFlagAndTheHelperPremultipliesWhenStraight()
    {
        string fx = Succeeds("uniform shader img; half4 main(float2 c) { return img.eval(c); }");

        fx.ShouldContain("static bool sd_StraightAlpha;", Case.Sensitive);
        fx.ShouldContain(
            "float4 sd_ChildColor(float4 c)\n{\n    return (sd_StraightAlpha ? float4((c.rgb * c.a), c.a) : c);\n}",
            Case.Sensitive);
        fx.ShouldContain(
            "float4 PSMain(VSOutput input) : COLOR0\n{\n    sd_StraightAlpha = false;\n" +
            "    return mainImage(input.UV * iResolution.xy);\n}\n",
            Case.Sensitive);
        fx.ShouldContain(
            "float4 PSMainStraightAlpha(VSOutput input) : COLOR0\n{\n    sd_StraightAlpha = true;\n" +
            "    float4 color = mainImage(input.UV * iResolution.xy);\n" +
            "    return float4(color.rgb / max(color.a, 0.0001), color.a);\n}\n",
            Case.Sensitive);
    }

    [Fact]
    public void Convert_CustomTechniqueName_NamesBothTechniques()
    {
        string fx = Succeeds(Plain, new ConvertOptions { TechniqueName = "Water" });

        fx.ShouldContain("technique Water\n", Case.Sensitive);
        fx.ShouldContain($"technique Water{SkSLToFxConverter.StraightAlphaTechniqueSuffix}\n", Case.Sensitive);
    }

    [Theory]
    [InlineData("half4 main(float2 p) { return half4(1); }")]
    [InlineData("float4 main(half2 p) { return float4(1); }")]
    [InlineData("vec4 main(vec2 p) { return vec4(1); }")]
    [InlineData("half4 main(const in float2 p) { return half4(1); }")]
    public void Convert_AcceptsEveryShaderEntrySpelling(string sksl) =>
        Succeeds(sksl).ShouldContain("float4 mainImage(float2 p)", Case.Sensitive);

    [Fact]
    public void Convert_NoMain_FailsLoudly() =>
        FailsWith("half4 foo(float2 c) { return half4(1); }", "main")
            .Message.ShouldContain("half4 main(float2 coord)", Case.Sensitive);

    [Fact]
    public void Convert_TwoMains_FailsAtTheSecond() =>
        FailsWith("half4 main(float2 a) { return half4(1); }\nhalf4 main(float2 b) { return half4(0); }", "main")
            .Line.ShouldBe(2);

    [Theory]
    [InlineData("half3 main(float2 p) { return half3(1); }")]
    [InlineData("float3 main(float2 p) { return float3(1); }")]
    [InlineData("half4 main(float3 p) { return half4(1); }")]
    public void Convert_NonColorEntry_IsRejected(string sksl) =>
        FailsWith(sksl, "main").Message.ShouldContain("must be 'half4 main(float2 coord)'", Case.Sensitive);

    [Fact]
    public void Convert_ColorFilterEntry_IsRejectedAsColorFilter() =>
        FailsWith("half4 main(half4 color) { return color.bgra; }", "main")
            .Message.ShouldContain("color filter", Case.Sensitive);

    [Fact]
    public void Convert_BlenderEntry_IsRejectedAsBlender() =>
        FailsWith("half4 main(half4 src, half4 dst) { return src; }", "main")
            .Message.ShouldContain("blender", Case.Sensitive);

    [Fact]
    public void Convert_ChildShaderEval_SamplesAtPixelCoordsTimesTexelSize()
    {
        ConvertResult r = SkSLToFxConverter.Convert(
            "uniform shader img; half4 main(float2 c) { return img.eval(c + float2(1, 0)); }");

        r.Success.ShouldBeTrue(string.Join("; ", r.Diagnostics.Select(d => d.Message)));
        r.Fx.ShouldNotBeNull();
        r.Fx.ShouldContain("sd_ChildColor(tex2D(img, (c + float2(1, 0)) * imgTexelSize))", Case.Sensitive);
        r.Fx.ShouldContain("texture imgTexture;", Case.Sensitive);
        r.Fx.ShouldContain("float2 imgTexelSize;", Case.Sensitive);
        r.UsedUniforms.ShouldBe(new[] { "iResolution", "img", "imgTexelSize" }, ignoreOrder: true);
    }

    [Fact]
    public void Convert_ChildWhoseNameEndsAnotherChild_RewritesEachOnItsOwn()
    {
        string fx = Succeeds(
            "uniform shader img; uniform shader myimg;\n" +
            "half4 main(float2 c) { return myimg.eval(c) + img.eval(c); }");

        fx.ShouldContain(
            "sd_ChildColor(tex2D(myimg, (c * myimgTexelSize))) + sd_ChildColor(tex2D(img, (c * imgTexelSize)))",
            Case.Sensitive);
        fx.ShouldNotContain("mytex", Case.Sensitive);
    }

    [Fact]
    public void Convert_EvalWithWhitespace_IsRewritten() =>
        Succeeds("uniform shader img; half4 main(float2 c) { return img . eval ( c ); }")
            .ShouldContain("tex2D(img, (c * imgTexelSize))", Case.Sensitive);

    [Fact]
    public void Convert_NestedEval_RewritesBoth() =>
        Succeeds("uniform shader img; half4 main(float2 p) { return img.eval(img.eval(p).xy * 10); }")
            .ShouldContain(
                "sd_ChildColor(tex2D(img, ((sd_ChildColor(tex2D(img, (p * imgTexelSize))).xy * 10) * imgTexelSize)))",
                Case.Sensitive);

    [Fact]
    public void Convert_UnbalancedEval_FailsAtTheCall()
    {
        ConvertDiagnostic d = FailsWith(
            "uniform shader img;\nhalf4 main(float2 p) { return img.eval(p; }", "img.eval");
        (d.Line, d.Column).ShouldBe((2, 31));
    }

    [Fact]
    public void Convert_EvalOnSomethingNotAChild_IsRejected() =>
        FailsWith("half4 main(float2 p) { return img.eval(p); }", "img.eval");

    [Fact]
    public void Convert_UserDeclaresTheReservedTexelSize_IsRejected() =>
        FailsWith(
            "uniform shader img; uniform float2 imgTexelSize; half4 main(float2 c) { return img.eval(c); }",
            "imgTexelSize").Message.ShouldContain("child shader 'img'", Case.Sensitive);

    [Fact]
    public void Convert_UserSizeUniformNamedLikeTheChild_IsFine() =>
        Succeeds("uniform shader img; uniform float2 imgSize; half4 main(float2 c) { return img.eval(c * imgSize); }")
            .ShouldContain("float2 imgSize;", Case.Sensitive);

    [Fact]
    public void Convert_IgnoresALineCommentThatLooksLikeMain() =>
        Succeeds("// half4 main(float2 q) old\nhalf4 main(float2 p) { return half4(1); }");

    [Fact]
    public void Convert_IgnoresUnsupportedConstructsInComments() =>
        Succeeds(
            "uniform shader img;\n" +
            "/* half4 main(float2 x) { return img.eval(x; sk_FragCoord; } */\n" +
            "half4 main(float2 p) { return img.eval(p); } // unpremul(layout(color))");

    [Fact]
    public void Convert_DiagnosticAfterABlockComment_KeepsTheOriginalPosition()
    {
        ConvertDiagnostic d = FailsWith("/* one\n two */ half4 main(float2 p) { return half4(sk_FragCoord); }", "sk_FragCoord");
        (d.Line, d.Column).ShouldBe((2, 45));
    }

    [Theory]
    [InlineData("half4 main(float2 p) { return half4(sk_FragCoord.xy, 0, 1); }", "sk_FragCoord", "coordinate passed to main")]
    [InlineData("layout(color) uniform half4 c; half4 main(float2 p) { return c; }", "layout", "plain half4/float4 uniform")]
    [InlineData("half4 main(float2 p) { return unpremul(half4(1)); }", "unpremul", "c.rgb / max(c.a, 0.0001)")]
    [InlineData("half4 main(float2 p) { return half4(toLinearSrgb(half3(1)), 1); }", "toLinearSrgb", "no working color space")]
    [InlineData("half4 main(float2 p) { return half4(fromLinearSrgb(half3(1)), 1); }", "fromLinearSrgb", "no working color space")]
    [InlineData("uniform colorFilter cf; half4 main(float2 p) { return half4(1); }", "colorFilter", "'uniform shader' children")]
    [InlineData("uniform blender b; half4 main(float2 p) { return half4(1); }", "blender", "'uniform shader' children")]
    [InlineData("uniform float2x3 m; half4 main(float2 p) { return half4(1); }", "float2x3", "Non-square")]
    [InlineData("uniform half4x2 m; half4 main(float2 p) { return half4(1); }", "half4x2", "Non-square")]
    [InlineData("half4 main(float2 p) { return half4(gl_FragCoord); }", "gl_FragCoord", "GLSL built-in")]
    [InlineData("half4 main(float2 p) { return half4(sk_Other); }", "sk_Other", "not an SkSL built-in")]
    [InlineData("uniform float3 iResolution; half4 main(float2 p) { return half4(p / iResolution.xy, 0, 1); }", "iResolution", "reserved")]
    [InlineData("uniform float iTime; half4 main(float2 p) { return half4(iTime); }", "iTime", "reserved")]
    [InlineData("uniform float sd_StraightAlpha; half4 main(float2 p) { return half4(sd_StraightAlpha); }", "sd_StraightAlpha", "'sd_' prefix")]
    [InlineData("half4 helper(float2 p) { float mainImage = 1; return half4(mainImage); } half4 main(float2 p) { return helper(p); }", "mainImage", "reserved")]
    public void Convert_UnsupportedSkSL_FailsWithAnSkSLDiagnostic(string sksl, string construct, string advice) =>
        FailsWith(sksl, construct).Message.ShouldContain(advice, Case.Sensitive);

    [Fact]
    public void Convert_ShaderAsAFunctionParameter_IsRejected()
    {
        ConvertResult r = SkSLToFxConverter.Convert(
            "uniform shader img;\n" +
            "half4 f(shader s, float2 p) { return s.eval(p); }\n" +
            "half4 main(float2 p) { return f(img, p); }");

        r.Success.ShouldBeFalse();
        ConvertDiagnostic d = r.Diagnostics.First(x => x.Construct == "shader");
        (d.Line, d.Column).ShouldBe((2, 9));
        d.Message.ShouldContain("call eval at the call site", Case.Sensitive);
        r.Diagnostics.ShouldContain(x => x.Construct == "s.eval");
    }

    [Fact]
    public void Convert_SquareMatrix_IsAccepted() =>
        Succeeds("uniform half2x2 m; half4 main(float2 p) { return half4(m * p, 0, 1); }")
            .ShouldContain("float2x2 m;", Case.Sensitive);

    [Fact]
    public void Convert_OptionsSettingOneField_KeepsTheSkSLDefaults()
    {
        string fx = Succeeds(Plain, new ConvertOptions { StopOnFirstError = true });

        fx.ShouldContain($"// {SkSLToFxConverter.DefaultEffectName} - generated", Case.Sensitive);
        fx.ShouldContain($"technique {SkSLToFxConverter.DefaultTechniqueName}\n", Case.Sensitive);
    }

    [Fact]
    public void Convert_OptionsNames_AreHonored()
    {
        string fx = Succeeds(Plain, new ConvertOptions { EffectName = "Water", TechniqueName = "Main" });

        fx.ShouldContain("// Water - generated", Case.Sensitive);
        fx.ShouldContain("technique Main\n", Case.Sensitive);
    }

    [Fact]
    public void Convert_CommonSource_IsRejected()
    {
        ConvertResult r = SkSLToFxConverter.Convert(Plain, new ConvertOptions { CommonSource = "float k;" });

        r.Success.ShouldBeFalse();
        r.Diagnostics.ShouldHaveSingleItem().Construct.ShouldBe("CommonSource");
    }
}
