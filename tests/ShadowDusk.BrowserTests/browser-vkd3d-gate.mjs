// The test hooks' success line: "OK:<base64 artifact>" then one FxcFormattedMessage per
// CompiledShader.Warnings entry, newline-separated (base64 never holds a newline).
function parseOk(res) {
  const payload = res.slice(3);
  const nl = payload.indexOf('\n');
  const b64 = nl < 0 ? payload : payload.slice(0, nl);
  return {
    artifact: Buffer.from(b64, 'base64'),
    warnings: nl < 0 ? [] : payload.slice(nl + 1).split('\n'),
  };
}
